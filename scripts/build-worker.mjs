import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const files=['src/core.js','api/generate.mjs','worker/index.js'];
const parts=await Promise.all(files.map(async name=>{
  const source=await readFile(new URL(name,root),'utf8');
  return `// Source: ${name}\n`+source.replace(/^import .+;\r?\n/gm,'').replace(/^export (?=(?:const|function|class|async function)\b)/gm,'');
}));
const output=new URL('worker/dashboard-worker.mjs',root);
await writeFile(output,'// Khai Cuoc dashboard bundle. MIT. Generated by scripts/build-worker.mjs.\n'+parts.join('\n\n'));
console.log('Built worker/dashboard-worker.mjs for the Cloudflare editor.');
